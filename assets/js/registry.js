export const toolById = new Map(tools.map((t) => [t.id, t]));
export const categoryById = new Map(categories.map((c) => [c.id, c]));

export function getTool(id) { return toolById.get(id) || null; }
export function toolsByCategory(catId) {
  return tools.filter((t) => t.categories.includes(catId)).sort((a, b) => b.popularity - a.popularity);
}
export function featuredTools() {
  return tools.filter((t) => t.featured).sort((a, b) => b.popularity - a.popularity);
}
export function popularTools(n = 8) { return [...tools].sort((a, b) => b.popularity - a.popularity).slice(0, n); }
export function recentTools(n = 6) {
  return [...tools].sort((a, b) => (a.added < b.added ? 1 : a.added > b.added ? -1 : b.popularity - a.popularity)).slice(0, n);
}
export function relatedTools(tool, n = 4) {
  if (tool.related) return tool.related.map(getTool).filter(Boolean).slice(0, n);
  const same = tools.filter((t) => t.id !== tool.id && t.categories.some((c) => tool.categories.includes(c)));
  same.sort((a, b) => {
    const shared = (x) => x.categories.filter((c) => tool.categories.includes(c)).length;
    return shared(b) - shared(a) || b.popularity - a.popularity;
  });
  return same.slice(0, n);
}

const STOP = new Set(['a','an','and','the','for','of','to','in','on','with','free','online','tool','tools','how','do','i','my','is','it','best','from','into','between','two']);
const norm = (s) => s.toLowerCase();

/** Score a tool against a query. Higher is better; 0 means no match. */
export function scoreTool(tool, query) {
  const q = norm(query).trim();
  if (!q) return 0;
  const terms = q.split(/\s+/).filter(Boolean);
  const name = norm(tool.name);
  const cat = norm(tool.categories.map((c) => categoryById.get(c)?.name || c).join(' '));
  const kw = norm([tool.name, ...(tool.keywords || []), ...(tool.aliases || []), cat].join(' '));
  const desc = norm(tool.blurb + ' ' + tool.description);
  let score = 0;
  for (const term of terms) {
    if (STOP.has(term) && terms.length > 1) continue;
    let t = 0;
    if (name === term) t = 220;
    else if (name.startsWith(term)) t = 150;
    else if (new RegExp(`\\b${term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`).test(name)) t = 120;
    else if ((tool.aliases || []).some((a) => norm(a) === q)) t = 140;
    else if ((tool.aliases || []).some((a) => norm(a).includes(term))) t = 100;
    else if (kw.includes(term)) t = 70;
    else if (desc.includes(term)) t = 30;
    if (t === 0 && term.length > 4) {
      // loose prefix match on any keyword word (handles plurals like "uuids")
      const words = kw.split(/[^a-z0-9+#]+/);
      if (words.some((w) => w.startsWith(term.slice(0, Math.max(4, term.length - 1))))) t = 45;
    }
    if (t === 0) return 0; // every term must match somewhere
    score = Math.max(score, t) + t * 0.1;
  }
  return score + tool.popularity * 0.05;
}

export function searchTools(query, limit = 20) {
  return tools
    .map((t) => [scoreTool(t, query), t])
    .filter(([s]) => s > 0)
    .sort((a, b) => b[0] - a[0])
    .slice(0, limit)
    .map(([, t]) => t);
}
